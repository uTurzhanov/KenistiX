using UnityEngine;
using UnityEngine.Video;

/// <summary>
/// Описание одного шага инструктажа.
/// Создаётся через меню: Assets > Create > Tutorial > Step
/// По одному ассету на каждый шаг (Шаг 1, Шаг 2, Шаг 3, Шаг 4...).
/// </summary>
[CreateAssetMenu(fileName = "NewTutorialStep", menuName = "Tutorial/Step")]
public class TutorialStepData : ScriptableObject
{
    [Header("Текст, отображаемый пользователю")]
    [Tooltip("Короткое название шага, например \"Вращение\" или \"Движение\". " +
             "Используется и в крупном заголовке, и (с автоматически подставленным номером) в списке шагов слева.")]
    public string stepTitle = "Движение";

    [Tooltip("СЛУЖЕБНОЕ поле для внутреннего использования (сценарий для записи озвучки, заметки) - " +
             "в самой панели НЕ отображается. Вся подача информации пользователю идёт через видео и озвучку, " +
             "текста на панели минимум (см. TutorialManager: только счётчик шага, название и список шагов).")]
    [TextArea(2, 4)]
    public string stepDescription = "Внутренняя заметка / черновик текста озвучки - на экране не показывается";

    [Header("Видео-подсказка (опционально, справа снизу)")]
    [Tooltip("Не обязательно для каждого шага - если у шага есть 3D-объект в сцене (Step Scene Object), видео можно не использовать вовсе.")]
    public VideoClip videoClip;
    public bool loopVideo = true;

    [Tooltip("Материал для RawImage конкретно на этом шаге - например разные хромакей-материалы " +
             "под разный цвет фона видео (чёрный/зелёный экран и т.п., один шейдер UIChromaKey, но " +
             "разные Material-ассеты с разным Key Color). Если пусто - остаётся материал, уже " +
             "назначенный на VideoFrame в редакторе (обычный без хромакея).")]
    public Material videoMaterial;

    [Header("3D-объект в сцене (опционально)")]
    [Tooltip("Например, модели контроллеров с анимацией вращения для шага 2. " +
             "TutorialManager включает (SetActive true) этот объект, пока идёт шаг, и выключает на остальных шагах. " +
             "Объект должен уже лежать в сцене (не в этом ассете) - сюда перетаскивается ссылка на него.")]
    public GameObject stepSceneObject;

    [Header("Озвучка шага (отдельная аудиодорожка, не встроенная в видео)")]
    public AudioClip narrationClip;

    [Header("Как определяется завершение шага")]
    public StepCompletionType completionType = StepCompletionType.Timer;

    [Header("Настройка детектора (только для Head Look Around)")]
    [Tooltip("Проверять поворот влево/вправо (Yaw) на этом шаге. Выключите, если шаг только про " +
             "вверх/вниз (например, разбили Head Look Around на два отдельных подшага).")]
    public bool headCheckYaw = true;

    [Tooltip("Проверять взгляд вверх/вниз (Pitch) на этом шаге. Выключите, если шаг только про " +
             "влево/вправо.")]
    public bool headCheckPitch = true;

    [Header("Настройка детектора (только для Thumbstick Activity)")]
    [Tooltip("Проверять движение (обычно левый стик) на этом шаге. Выключите, если шаг только про поворот.")]
    public bool thumbstickCheckMove = true;

    [Tooltip("Проверять поворот (обычно правый стик) на этом шаге. Выключите, если шаг только про движение.")]
    public bool thumbstickCheckTurn = true;

    [Header("Кнопка «Далее»")]
    [Tooltip("Показывать ли саму кнопку «Далее» на этом шаге. Чтобы физически нажать её, нужно " +
             "навести луч контроллера на панель И нажать курок - этому нигде явно не учим, поэтому " +
             "на ранних шагах (пока пользователь не освоился с прицеливанием и нажатием) разумно " +
             "держать выключенным - переход всё равно произойдёт сам по детектору/озвучке/страховке. " +
             "Включайте там, где кнопка реально имеет смысл как осознанный запасной вариант.")]
    public bool showNextButton = true;

    [Tooltip("Максимальное время ожидания ПОСЛЕ того, как доиграет основная озвучка (Narration Clip) " +
             "и реально включится отслеживание действия - если за это время реальное действие не " +
             "отследилось (трекинг подвёл/пользователь застрял), шаг переключится САМ. Кнопка «Далее» " +
             "при этом тоже станет доступна (если включена выше), но нажимать её не обязательно.\n" +
             "Для Timer-шагов (без детектора) не используется вовсе - переход происходит сразу по " +
             "окончании озвучки, этому значению тут просто нечего добавить.")]
    [Min(0f)]
    public float delayBeforeNextButton = 5f;

    [Header("Панель (опционально)")]
    [Tooltip("Открепить панель от камеры на этом шаге - Canvas временно переключается из Screen " +
             "Space - Camera в World Space, панель остаётся висеть в комнате там, где была в момент " +
             "переключения, и больше не следует за головой. Полезно на шагах вроде захвата предмета, " +
             "где панель перед глазами мешает дотянуться до объекта. Автоматически прикрепляется " +
             "обратно на следующем шаге, где этот флаг выключен.")]
    public bool detachPanelFromCamera = false;

    [Header("Закрепление результата (опционально)")]
    [Tooltip("После ПЕРВОГО успешного выполнения действия на этом шаге - не переходить дальше сразу, " +
             "а проиграть Reinforcement Narration Clip (из TutorialManager) и попросить повторить то " +
             "же самое действие ещё раз. Полезно для шагов вроде поворота головы или стиков, чтобы " +
             "пользователь закрепил навык, а не просто случайно задел действие один раз.")]
    public bool requireReinforcementRepeat = false;

    [Header("Опционально")]
    [Tooltip("Текст на кнопке для этого шага. Если пусто — используется значение по умолчанию из TutorialManager")]
    public string customButtonLabel;
}

/// <summary>Способ, которым определяется, что пользователь выполнил действие шага и можно идти дальше.</summary>
public enum StepCompletionType
{
    /// <summary>Просто ждём фиксированное время (старое поведение, без реального трекинга).</summary>
    Timer,
    /// <summary>Шаг 1: пользователь реально повернул голову и осмотрелся.</summary>
    HeadLookAround,
    /// <summary>Шаг 2: пользователь реально покрутил контроллер в руке.</summary>
    ControllerRotation,
    /// <summary>Шаг 3: пользователь реально подвигал стиком движения И стиком поворота.</summary>
    ThumbstickActivity,
    /// <summary>Шаг 4: пользователь реально нажал нужную кнопку.</summary>
    ButtonPress,
    /// <summary>Шаг 7: пользователь реально захватил (взял) предмет в сцене.</summary>
    ObjectGrab,
}